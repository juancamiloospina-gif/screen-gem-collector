WITH etapas AS (
  SELECT e.etapa, e.ord FROM unnest(enum_range(NULL::public.etapa_caso)) WITH ORDINALITY AS e(etapa, ord)
)
INSERT INTO public.eventos_caso (caso_id, etapa, ocurrido_en)
SELECT c.id,
       et.etapa,
       c.creado_en + ((et.ord - 1)::numeric * (EXTRACT(epoch FROM (now() - c.creado_en)) / GREATEST(cur.ord - 1, 1)) * interval '1 second')
FROM public.casos c
JOIN etapas cur ON cur.etapa = c.etapa
JOIN etapas et ON et.ord <= cur.ord;
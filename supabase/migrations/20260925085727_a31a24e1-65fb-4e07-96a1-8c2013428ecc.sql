CREATE TYPE public.etapa_caso AS ENUM (
  'Creación','Trámite','Asignado','Llegada a sitio','En atención','Traslado','Finalizado','Cierre'
);

CREATE TABLE public.casos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1040) UNIQUE,
  placa text NOT NULL,
  tipo_servicio text NOT NULL,
  ciudad text NOT NULL,
  ubicacion text NOT NULL DEFAULT '',
  tipo_vehiculo text NOT NULL DEFAULT 'Pesado',
  etapa public.etapa_caso NOT NULL DEFAULT 'Creación',
  prometido_min integer NOT NULL DEFAULT 45,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  mapa_x numeric NOT NULL DEFAULT 40,
  mapa_y numeric NOT NULL DEFAULT 40,
  origen text NOT NULL DEFAULT 'Agente IA'
);

CREATE TABLE public.eventos_caso (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  caso_id uuid NOT NULL REFERENCES public.casos(id) ON DELETE CASCADE,
  etapa public.etapa_caso NOT NULL,
  ocurrido_en timestamptz NOT NULL DEFAULT now(),
  nota text
);

CREATE INDEX eventos_caso_caso_id_idx ON public.eventos_caso(caso_id);

GRANT SELECT, INSERT, UPDATE ON public.casos TO anon, authenticated;
GRANT SELECT, INSERT ON public.eventos_caso TO anon, authenticated;
GRANT ALL ON public.casos TO service_role;
GRANT ALL ON public.eventos_caso TO service_role;

ALTER TABLE public.casos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eventos_caso ENABLE ROW LEVEL SECURITY;

